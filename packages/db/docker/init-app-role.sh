#!/bin/sh
# Runs once on first Postgres start (docker-entrypoint-initdb.d).
# POSTGRES_USER owns the schema and runs migrations; APP_DB_USERNAME is the least-privilege runtime role.
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-SQL
  CREATE ROLE "$APP_DB_USERNAME" LOGIN PASSWORD '$APP_DB_PASSWORD' NOSUPERUSER NOCREATEDB NOCREATEROLE;
  GRANT CONNECT ON DATABASE "$POSTGRES_DB" TO "$APP_DB_USERNAME";
  GRANT USAGE ON SCHEMA public TO "$APP_DB_USERNAME";
  ALTER DEFAULT PRIVILEGES FOR ROLE "$POSTGRES_USER" IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "$APP_DB_USERNAME";
  ALTER DEFAULT PRIVILEGES FOR ROLE "$POSTGRES_USER" IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO "$APP_DB_USERNAME";
SQL
